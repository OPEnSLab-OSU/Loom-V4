#include "Loom_BatchSD.h"
#include "Logger.h"

//////////////////////////////////////////////////////////////////////////////////////////////////////
Loom_BatchSD::Loom_BatchSD(Loom_Hypnos &hypnos, int batchSize) : batchSize(batchSize) {
    sdMan = hypnos.getSDManager();
    if (sdMan == nullptr) {
        ERROR(F("BatchSD requires Hypnos SD support to be enabled."));
        this->batchSize = 0;
        return;
    }

    if (batchSize <= 0) {
        ERROR(F("BatchSD requires a positive batch size."));
        this->batchSize = 0;
        return;
    }

    sdMan->setBatchSize(batchSize);
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
bool Loom_BatchSD::shouldPublish() {
    return sdMan != nullptr && batchSize > 0 && sdMan->getCurrentBatch() >= batchSize;
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
File &Loom_BatchSD::getBatch() { return sdMan->getFile(sdMan->getBatchFilename()); }
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
bool Loom_BatchSD::markPublished() { return sdMan != nullptr && sdMan->clearBatch(); }
//////////////////////////////////////////////////////////////////////////////////////////////////////
