#include "Loom_Relay.h"
#include "Logger.h"

//////////////////////////////////////////////////////////////////////////////////////////////////////
Loom_Relay::Loom_Relay(const byte controlPin)
    : Actuator(ACTUATOR_TYPE::RELAY, 0), manInst(nullptr), pin(controlPin) {
    char name[MODULE_NAME_SIZE];
    snprintf(name, sizeof(name), "%s%u", typeToString(), pin);
    setModuleName(name);
    pinMode(controlPin, OUTPUT);
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
Loom_Relay::Loom_Relay(Manager &man, const byte controlPin)
    : Actuator(ACTUATOR_TYPE::RELAY, 0), manInst(&man), pin(controlPin) {
    char name[MODULE_NAME_SIZE];
    snprintf(name, sizeof(name), "%s%u", typeToString(), pin);
    setModuleName(name);
    pinMode(controlPin, OUTPUT);
    manInst->registerModule(this);
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
void Loom_Relay::control(JsonArray json) {
    FUNCTION_START;
    // Update the state
    setState(json[0].as<bool>());
    FUNCTION_END;
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
void Loom_Relay::package(JsonObject json) {
    FUNCTION_START;
    json["State"] = state ? "HIGH" : "LOW";
    FUNCTION_END;
}
//////////////////////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////////////////////
void Loom_Relay::setState(bool state) {
    FUNCTION_START;
    this->state = state;
    digitalWrite(pin, state ? HIGH : LOW);
    LOGF("Relay pin is set to: %s", state ? "HIGH" : "LOW");
    FUNCTION_END;
}
