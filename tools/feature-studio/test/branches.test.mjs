import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readBranches, switchBranch } from '../branches.mjs';
import { startStudio } from '../server.mjs';
const execute = promisify(execFile);

test('branch selection only switches existing local branches and preserves conflicting local edits', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'feature-branch-test-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const hooks = path.join(root, 'empty-hooks'); await mkdir(hooks);
  const git = args => execute('git', ['-C', root, '-c', 'user.name=Feature Studio test', '-c', 'user.email=studio@example.invalid', '-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=' + hooks, ...args], { windowsHide: true });
  await git(['init', '-b', 'base']);
  const file = path.join(root, 'example.txt');
  await writeFile(file, 'base'); await git(['add', 'example.txt']); await git(['commit', '-m', 'Base fixture']);
  await git(['switch', '-c', 'other']);
  await writeFile(file, 'other'); await git(['commit', '-am', 'Other fixture']);
  await switchBranch(root, 'base');
  assert.equal((await readBranches(root)).branch, 'base');
  assert.equal(await readFile(file, 'utf8'), 'base');
  await writeFile(file, 'unsaved local work');
  await assert.rejects(switchBranch(root, 'other'), /Git kept the current checkout/);
  assert.equal((await readBranches(root)).branch, 'base');
  assert.equal(await readFile(file, 'utf8'), 'unsaved local work');
  await assert.rejects(switchBranch(root, '--force'), /existing local branch/);
});

test('branch switches rebuild changed example graphs and APIs, remove absent recipes, and reuse matching checkout caches', async t => {
  const temp=await mkdtemp(path.join(os.tmpdir(),'feature-branch-recipes-')),root=path.join(temp,'repo'),workspace=path.join(temp,'local');
  await mkdir(root);const hooks=path.join(temp,'empty-hooks');await mkdir(hooks);
  const git=args=>execute('git',['-C',root,'-c','user.name=Feature Studio test','-c','user.email=studio@example.invalid','-c','commit.gpgsign=false','-c','core.hooksPath='+hooks,...args],{windowsHide:true});
  await git(['init','-b','base']);await mkdir(path.join(root,'src'));await mkdir(path.join(root,'examples','Probe'),{recursive:true});
  const header=path.join(root,'src','Probe.h'),sketch=path.join(root,'examples','Probe','Probe.ino');
  const code='Manager manager("Device",1);\nLoom_Probe probe(manager);\nvoid setup(){manager.initialize();}\nvoid loop(){probe.measure();}\n';
  await writeFile(header,'class Manager {public:Manager(const char *name,int id);void initialize();};\nclass Loom_Probe {public:Loom_Probe(Manager &man);void measure();};');
  await writeFile(sketch,code);await git(['add','.']);await git(['commit','-m','Base recipes']);
  await git(['switch','-c','example-only']);await writeFile(sketch,code.replace('probe.measure();','probe.measure();probe.measure();'));await git(['commit','-am','Change only the example']);
  await git(['switch','-c','code-and-examples']);
  await writeFile(header,(await readFile(header,'utf8')).replace('void measure();','void measure();void calibrate();'));
  await mkdir(path.join(root,'examples','Calibrate'));await writeFile(path.join(root,'examples','Calibrate','Calibrate.ino'),code.replace('probe.measure();','probe.calibrate();probe.measure();'));
  await git(['rm','examples/Probe/Probe.ino']);await git(['add','.']);await git(['commit','-m','API and replacement example']);await git(['switch','base']);
  const app=await startStudio({root,workspace,port:0});
  t.after(async()=>{await new Promise(resolve=>{app.server.close(resolve);app.server.closeAllConnections();});await rm(temp,{recursive:true,force:true});});
  const get=async route=>(await fetch(app.url+route)).json();
  const post=async(route,body)=>{const r=await fetch(app.url+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const result=await r.json();assert.equal(r.status,200,JSON.stringify(result));return result;};
  const base=await get('/api/state');
  assert.equal(base.preparation.recipeCount,1);
  await post('/api/branch',{branch:'example-only'});
  const exampleOnly=await get('/api/state');assert.notEqual(exampleOnly.sourceFingerprint,base.sourceFingerprint,'example changes alone invalidate results');
  assert.equal(exampleOnly.preparation.cacheHit,false);assert.equal(exampleOnly.sourceBranch,'example-only');
  const twice=await post('/api/example',{path:'examples/Probe/Probe.ino'});
  assert.equal(twice.assembly.nodes.filter(n=>n.reason.includes('probe.measure()')).length,2,'changed source creates the new graph automatically');
  const requested=structuredClone(twice.design);
  await post('/api/branch',{branch:'code-and-examples'});
  const changed=await get('/api/state'),catalog=await get('/api/catalog'),recipes=await get('/api/examples');
  assert.deepEqual(changed.design,requested,'switching branches preserves requested features');assert.equal(changed.assembly,null,'old branch output is not presented as current');
  assert.ok(catalog.blocks.find(b=>b.className==='Loom_Probe').methods.includes('calibrate()'));
  assert.deepEqual(recipes.examples.map(e=>e.path),['examples/Calibrate/Calibrate.ino']);
  const replacement=await post('/api/example',{path:'examples/Calibrate/Calibrate.ino'});
  assert.ok(replacement.assembly.nodes.some(n=>n.reason.includes('probe.calibrate()')));
  await post('/api/branch',{branch:'base'});const back=await get('/api/state');
  assert.equal(back.preparation.revision,base.preparation.revision);assert.equal(back.preparation.cacheHit,true);
  const original=await post('/api/example',{path:'examples/Probe/Probe.ino'});
  assert.equal(original.assembly.nodes.filter(n=>n.reason.includes('probe.measure()')).length,1);
});
