test('project tabs preserve independent results, reopen after restart, confirm deletion and round-trip complete exports', async t => {
  const temp = await mkdtemp(path.join(os.tmpdir(), 'studio-projects-'));
  const root = path.join(temp, 'repo'), workspace = path.join(temp, 'local');
  await mkdir(path.join(root, 'src'), { recursive: true });
  await mkdir(path.join(root, 'examples', 'Probe'), { recursive: true });
  await writeFile(path.join(root, 'src', 'Probe.h'), 'class Manager { public: Manager(const char *name, int id); };\nclass Loom_Probe { public: Loom_Probe(Manager &man); };');
  const source = 'Manager manager("Device", 1);\nLoom_Probe probe(manager);\nvoid setup(){manager.initialize();}\nvoid loop(){manager.measure(); manager.package(); manager.pause(5000);}\n';
  await writeFile(path.join(root, 'examples', 'Probe', 'Probe.ino'), source);
  let app = await startStudio({ root, workspace, port: 0 });
  const close = () => new Promise(resolve => { app.server.close(resolve); app.server.closeAllConnections(); });
  t.after(async () => { await close(); await rm(temp, { recursive: true, force: true }); });
  const get = async route => (await fetch(app.url + route)).json();
  const post = async (route, body = {}, status = 200) => {
    const response = await fetch(app.url + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const result = await response.json(); assert.equal(response.status, status, JSON.stringify(result)); return result;
  };
  let state = await get('/api/state');
  const first = state.projects.activeId;
  const original = { ...state.design, name: 'My sensor', description: 'Log every five minutes' };
  await post('/api/design', { projectId: first, design: original });
  assert.equal((await get('/api/history')).canUndo,true);
  await post('/api/history/undo');assert.equal((await get('/api/state')).design.name,'Untitled application');
  await post('/api/history/redo');assert.deepEqual((await get('/api/state')).design,original);
  await post('/api/example', { path: 'examples/Probe/Probe.ino' });
  state = await get('/api/state');
  const exampleId = state.projects.activeId;
  assert.notEqual(exampleId, first); assert.equal(state.projects.openIds.length, 2);
  assert.equal(state.assembly.files[0].content, source);
  const beforeRename = structuredClone(state.assembly);
  await post('/api/design', { projectId: exampleId, design: { ...state.design, name: 'Renamed probe demo' } });
  state = await get('/api/state');
  assert.equal(state.design.name, 'Renamed probe demo'); assert.equal(state.assemblyOrigin, 'example');
  await post('/api/history/undo');assert.equal((await get('/api/state')).design.name,'Probe');
  await post('/api/history/redo');state=await get('/api/state');assert.equal(state.design.name,'Renamed probe demo');
  assert.deepEqual({ ...state.assembly, designRevision: beforeRename.designRevision }, beforeRename, 'rename preserves graph, source links, notes and code');
  const expected = structuredClone(state);
  const bundle = await get('/api/project-export');
  assert.equal(bundle.format, 'feature-studio/project');
  assert.deepEqual(bundle.design, expected.design); assert.deepEqual(bundle.assembly, expected.assembly);
  assert.equal(bundle.origin.kind, 'example'); assert.ok(bundle.source.fingerprint);
  await post('/api/design/new');
  state = await get('/api/state'); const blankId = state.projects.activeId;
  assert.equal(state.projects.openIds.length, 3); assert.equal(state.assembly, null);
  await post('/api/design', { projectId: first, design: original }, 400);
  await post('/api/projects/open', { id: first });
  state = await get('/api/state'); assert.deepEqual(state.design, original); assert.equal(state.assembly, null);
  assert.equal(state.projects.items.find(p => p.id === exampleId).name, expected.design.name, 'switching does not rename the old tab');
  await post('/api/projects/open', { id: exampleId });
  state = await get('/api/state'); assert.deepEqual(state.assembly, expected.assembly);
  await post('/api/projects/close', { id: exampleId });
  state = await get('/api/state'); assert.ok(!state.projects.openIds.includes(exampleId));
  assert.ok(state.projects.items.some(p => p.id === exampleId), 'closing keeps the project in recipes');
  await close(); app = await startStudio({ root, workspace, port: 0 });
  await post('/api/projects/open', { id: exampleId });
  state = await get('/api/state'); assert.deepEqual(state.assembly, expected.assembly); assert.equal(state.assemblyOrigin, 'example');
  assert.ok(state.history.canUndo,'history survives an app restart');
  await post('/api/projects/import', bundle);
  state = await get('/api/state'); const importedId = state.projects.activeId;
  assert.notEqual(importedId, exampleId); assert.deepEqual(state.design, bundle.design); assert.deepEqual(state.assembly, bundle.assembly);
  assert.equal(await (await fetch(app.url + '/api/download?file=' + bundle.assembly.files[0].name)).text(), source);
  await post('/api/projects/delete', { id: importedId }, 400);
  assert.equal((await get('/api/state')).projects.activeId, importedId, 'unconfirmed deletion changes nothing');
  await post('/api/projects/delete', { id: importedId, confirm: true });
  state = await get('/api/state'); assert.ok(!state.projects.items.some(p => p.id === importedId));
  assert.equal((await get('/api/examples')).examples.length, 1, 'checkout example is never removed');
  await post('/api/projects/open', { id: '../outside' }, 400);
  const stale = structuredClone(bundle); stale.assembly.sourceFingerprint = 'another-checkout';
  await post('/api/projects/import', stale, 400);
  assert.deepEqual((await get('/api/state')).projects, state.projects, 'invalid imports leave tabs intact');
  await post('/api/projects/open', { id: exampleId });
  state = await get('/api/state');
  await post('/api/design', { projectId: exampleId, design: { ...state.design, description: 'Change the sample interval later' } });
  state = await get('/api/state');
  assert.equal(state.assembly, null); assert.deepEqual(state.lastBuild.assembly, expected.assembly, 'editing retains the previous reviewed result');
  assert.deepEqual(state.lastBuild.design,expected.design,'the previous requests stay frozen for comparison');
  await post('/api/projects/open', { id: blankId }); await post('/api/projects/open', { id: exampleId });
  state = await get('/api/state'); assert.equal(state.assembly, null); assert.deepEqual(state.lastBuild.assembly, expected.assembly, 'switching tabs never erases the last result');
  await post('/api/design',{projectId:exampleId,design:expected.design});
  state=await get('/api/state');assert.deepEqual(state.assembly,expected.assembly,'manually restoring the original requests reuses the matching result');
  await post('/api/design',{projectId:exampleId,design:{...state.design,description:'Change the sample interval later'}});
  assert.deepEqual((await get('/api/project-export')).lastBuild.assembly, expected.assembly, 'draft exports include the last build too');
  assert.equal(await (await fetch(app.url + '/api/download?lastBuild=true&file=' + expected.assembly.files[0].name)).text(), source);
  await post('/api/history/undo');state=await get('/api/state');assert.deepEqual(state.assembly,expected.assembly,'undo restores the matching reviewed build');
  await post('/api/history/redo');assert.equal((await get('/api/state')).assembly,null);
  await post('/api/history/undo');state=await get('/api/state');
  await post('/api/design',{projectId:exampleId,design:{...state.design,description:'A different edit after undo'}});
  assert.equal((await get('/api/history')).canRedo,false,'a new edit branches from the selected history version');
  for (const id of (await get('/api/projects')).openIds) await post('/api/projects/close', { id });
  state = await get('/api/state'); assert.equal(state.projects.openIds.length, 1); assert.equal(state.design.blocks.length, 0);
  await post('/api/projects/open', { id: blankId },400);
  assert.equal((await get('/api/state')).projects.items.filter(project=>project.draft).length,1,'closed empty drafts are not retained as saved recipes');
});

test('older checkout imports preserve requests and assembled files without automatically building or flashing', async t => {
  const temp = await mkdtemp(path.join(os.tmpdir(), 'studio-portability-'));
  const root = path.join(temp, 'repo'), workspace = path.join(temp, 'local');
  await mkdir(path.join(root, 'src'), { recursive: true });
  await mkdir(path.join(root, 'examples', 'Probe'), { recursive: true });
  const header = path.join(root, 'src', 'Probe.h');
  await writeFile(header, 'class Manager {};\nclass Loom_Probe {};');
  const source = 'Manager manager("Device", 1);\nLoom_Probe probe(manager);\nvoid setup(){manager.initialize();}\nvoid loop(){manager.measure();}\n';
  await writeFile(path.join(root, 'examples', 'Probe', 'Probe.ino'), source);
  let executions = 0;
  let app;
  const start = async () => { app = await startStudio({ root, workspace, port: 0, arduinoExecute: async () => { executions++; return ''; } }); };
  const close = () => new Promise(resolve => { app.server.close(resolve); app.server.closeAllConnections(); });
  t.after(async () => { await close(); await rm(temp, { recursive: true, force: true }); });
  const get = async route => (await fetch(app.url + route)).json();
  const post = async (route, body, status = 200) => {
    const response = await fetch(app.url + route, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body || {}) });
    const result = await response.json(); assert.equal(response.status, status, JSON.stringify(result)); return result;
  };
  await start();
  await post('/api/example', { path: 'examples/Probe/Probe.ino' });
  const bundle = await get('/api/project-export');
  const originalId = (await get('/api/state')).projects.activeId;
  await close();
  // A branch/update may change examples and remove classes. Inputs must survive.
  await writeFile(header, 'class Manager {};\nclass Loom_Replacement {};');
  await writeFile(path.join(root, 'examples', 'Probe', 'Probe.ino'), source + '// updated checkout\n');
  await start();
  await post('/api/projects/import', bundle);
  let state = await get('/api/state'); const importedId = state.projects.activeId;
  assert.notEqual(state.sourceFingerprint, bundle.assembly.sourceFingerprint);
  assert.deepEqual(state.design, bundle.design);
  assert.equal(state.assembly, null);
  assert.deepEqual(state.lastBuild.assembly, bundle.assembly);
  assert.deepEqual(state.lastBuild.design, bundle.design);
  assert.deepEqual(state.lastBuild.origin, bundle.origin);
  assert.equal(await (await fetch(app.url + '/api/download?lastBuild=true&file=' + bundle.assembly.files[0].name)).text(), source);
  const callsBefore = executions;
  assert.ok((await get('/api/device/projects')).projects.find(project=>project.id===importedId).hasCode,'saved assembled files remain selectable for an explicit build');
  for (const action of ['build', 'flash']) {
    const error = await post('/api/device/' + action, { projectId: importedId }, 400);
    assert.match(error.error, /Choose an installed board|Build the current code/);
  }
  assert.equal(executions, callsBefore, 'import and incomplete build/flash requests do not run tools');
  const exported = await get('/api/project-export');
  assert.equal(exported.assembly, null); assert.deepEqual(exported.lastBuild.assembly, bundle.assembly);
  await post('/api/projects/open', { id: originalId });
  assert.deepEqual((await get('/api/state')).lastBuild.assembly, bundle.assembly, 'older saved tabs retain their build too');
  await post('/api/projects/open', { id: importedId });
  await close(); await start();
  state = await get('/api/state'); assert.equal(state.assembly, null); assert.deepEqual(state.lastBuild.assembly, bundle.assembly);
  await post('/api/projects/import', exported);
  assert.deepEqual((await get('/api/state')).lastBuild.assembly, bundle.assembly, 'historical builds round-trip repeatedly');
  const before = (await get('/api/state')).projects;
  const malformed = structuredClone(exported); malformed.lastBuild.assembly.files[0].name = '../outside.ino';
  await post('/api/projects/import', malformed, 400);
  assert.deepEqual((await get('/api/state')).projects, before, 'malformed history is rejected before creating a tab');
  await post('/api/projects/import', bundle.design);
  state = await get('/api/state'); assert.deepEqual(state.design, bundle.design); assert.equal(state.assembly, null); assert.equal(state.lastBuild, null);
});
